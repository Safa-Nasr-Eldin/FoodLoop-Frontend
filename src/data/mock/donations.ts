export function getMockDonations(): Donation[] {
  return DONATIONS
}

export function getMockDonationById(id: string): Donation | undefined {
  return DONATIONS.find((d) => d.id === id)
}

/** Open listings, soonest to close first. */
export function getMockMarketplaceDonations(): Donation[] {
  return DONATIONS.filter((d) => d.status === 'Available').sort((a, b) => a.expiresAt.localeCompare(b.expiresAt))
}

/** Everything one organization has listed, most recently updated first. */
export function getMockOrganizationDonations(organizationId: string): Donation[] {
  return DONATIONS.filter((d) => d.organizationId === organizationId).sort((a, b) =>
    b.updatedAt.localeCompare(a.updatedAt),
  )
}
